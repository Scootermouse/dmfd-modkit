"""Developers only: fills mod/ with the recolored test classes (shipped in Test Classes since 0.8) for checking many
classes at once (paging, empty spaces, online). Each test class's base is the class whose
spot it takes on its page (class % 6), so the base's select / portrait / HUD art fits; all
its art and its body palette are the base's, hue-rotated. NO_ART classes get no pictures
(they show the empty picture everywhere).

    python -I tools/make_test_classes.py          make / refresh them
    python -I tools/make_test_classes.py --remove take them out again
"""
import colorsys, csv, io, os, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import layout, osb, osbedit, palettes, selectart, sprites  # noqa: E402

MOD = os.path.join(os.path.dirname(HERE), "mod")
CLASSES = [7, 8, 9, 10, 11, 13, 14, 15, 16, 17, 18, 19, 20]
NO_ART = {17}
BASES = ["empress", "warrior", "shinobi", "witch", "oracle", "bandit"]
TAG = "generated by make_test_classes.py"


def rotate(img, deg, min_sat=0.3):
    px = bytearray(img)
    for i in range(0, len(px), 4):
        if not px[i + 3]:
            continue
        h, l, s = colorsys.rgb_to_hls(*(c / 255 for c in px[i:i + 3]))
        if s > min_sat:
            px[i:i + 3] = bytes(int(c * 255 + .5) for c in colorsys.hls_to_rgb((h + deg / 360) % 1, l, s))
    return bytes(px)


def save_mesh(b, mesh, deg, path_stem):
    """Render one picture with the exporter's margin/origin naming, recolored."""
    x0, y1, w, h = sprites.canvas(b, [mesh])
    M = sprites.MARGIN
    box = (x0 - M, y1 + M, w + 2 * M, h + 2 * M)
    W, H, imgs = sprites.render(b, [mesh], None, box)
    rel = "select_art/%s_m%d_o%d_%d.png" % (path_stem, mesh, box[0], box[1])
    osb.write_png(os.path.join(MOD, rel), W, H, rotate(imgs[0], deg))
    return rel


def art_for(cls, k, deg, banks):
    s0a, icon, s200, cp = banks
    nm = selectart.HUD_FACE_NAMES[k]
    root = lambda b, n: selectart._root(b, layout.ice(n))[1]
    stem = "test%d_" % cls
    return {
        "panel_art": save_mesh(s0a, selectart.panel_mesh(osbedit.parse(s0a), k), deg, stem + "panel"),
        "highlight_art": save_mesh(s0a, root(s0a, selectart.HIGHLIGHTS[k]), deg, stem + "highlight"),
        "portrait_art": save_mesh(icon, root(icon, "PlIcon_%d" % (k + 1)), deg, stem + "portrait"),
        "portrait_large_art": save_mesh(icon, root(icon, "PlIcon_%d_24" % (k + 1)), deg, stem + "portrait_large"),
        "bar_face_art": save_mesh(s200, root(s200, "PlFace_%d" % (k + 1)), deg, stem + "bar_face"),
        "hud_face_art": save_mesh(cp, root(cp, nm + "顔01"), deg, stem + "hud_face1"),
        "hud_face2_art": save_mesh(cp, root(cp, nm + "顔02"), deg, stem + "hud_face2"),
        "hud_frame_art": save_mesh(cp, root(cp, nm + "ライフ"), deg, stem + "hud_frame"),
    }


def remove_files():
    for c in CLASSES:
        p = os.path.join(MOD, "palettes")
        for f in os.listdir(p):
            if f.startswith("pl%d_pal from " % c):
                os.remove(os.path.join(p, f))
        shutil.rmtree(os.path.join(MOD, "sprites", "pl%d_cb00" % c), ignore_errors=True)
    sa = os.path.join(MOD, "select_art")
    for f in os.listdir(sa):
        if f.startswith("test") and f[4:].split("_")[0].isdigit():
            os.remove(os.path.join(sa, f))


def main():
    path = os.path.join(MOD, "classes.csv")
    raw = open(path, encoding="utf-8-sig", newline="").read()
    rows = [r for r in csv.reader(io.StringIO(raw)) if r]
    hdr = rows[0]
    keep = [r for r in rows[1:] if TAG not in r[hdr.index("notes")]]
    remove_files()
    if "--remove" not in sys.argv:
        banks = [sprites.load("Win/%s.osb" % n) for n in ("s_o0a00", "com_pl_icon", "s_o0200", "cp_o0000")]
        for i, c in enumerate(CLASSES):
            k = c % 6
            deg = 40 + (i * 97) % 280  # spread out, never close to the original
            # body: a copy of the base's; palette: the base's, hue-rotated
            os.makedirs(os.path.join(MOD, "sprites", "pl%d_cb00" % c), exist_ok=True)
            open(os.path.join(MOD, "sprites", "pl%d_cb00" % c, "_source.txt"), "w").write("pl%d_cb00\n" % k)
            tmp = os.path.join(MOD, "palettes", "_tmp.png")
            palettes.export_png(sprites.load("Win/pl%d_pal.osb" % k), tmp)
            w, h, img = osb.read_png_rgba(tmp)
            os.remove(tmp)
            osb.write_png(os.path.join(MOD, "palettes", "pl%d_pal from pl%d_pal.png" % (c, k)), w, h, rotate(img, deg))
            row = dict.fromkeys(hdr, "")
            if "id" in row:  # a unique name that keeps the old order (the combiner numbers by id)
                row["id"] = "t%03d_test_%d_%s" % (c, c, BASES[k])
            row.update({"class": str(c), "base": BASES[k], "body": "pl%d_cb00" % c, "palette": "pl%d_pal" % c,
                        "name": "TEST %d %s" % (c, BASES[k].upper()),
                        "description": "CLASS %d - PAGE %d\nA recolored %s for\ntesting many classes%s." %
                                       (c, c // 6 + 1, BASES[k].capitalize(),
                                        "\n(no pictures of its own)" if c in NO_ART else ""),
                        "notes": "%s (hue +%d)" % (TAG, deg)})
            if c not in NO_ART:
                row.update(art_for(c, k, deg, banks))
            keep.append([row[h] for h in hdr])
            print("class %d: %s, hue +%d%s" % (c, BASES[k], deg, ", no art" if c in NO_ART else ""))
    keep.sort(key=lambda r: int(r[0]))
    out = io.StringIO()
    csv.writer(out, lineterminator="\r\n" if "\r\n" in raw else "\n").writerows([hdr] + keep)
    open(path, "w", encoding="utf-8-sig", newline="").write(out.getvalue())
    print("classes.csv: %d class(es). Now run Build mod." % len(keep))


if __name__ == "__main__":
    main()
