"""Generate the winmm.dll forwarding stubs from the real 32-bit system DLL.

Writes src/winmm.def and src/winmm_exports.inc. Rerun only if Windows' winmm
changes its export list (it practically never does).
usage: python -I tools/gen_winmm_proxy.py
"""
import os
import struct

SRC = r"C:\Windows\SysWOW64\winmm.dll"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

d = open(SRC, "rb").read()
pe = struct.unpack_from("<I", d, 0x3C)[0]
nsec = struct.unpack_from("<H", d, pe + 6)[0]
opt = pe + 24
assert struct.unpack_from("<H", d, opt)[0] == 0x10B, "need the 32-bit winmm"
exp_rva = struct.unpack_from("<I", d, opt + 96)[0]
secs = []
so = opt + struct.unpack_from("<H", d, pe + 20)[0]
for i in range(nsec):
    _, vsz, va, rsz, rp = struct.unpack_from("<8sIIII", d, so + 40 * i)
    secs.append((va, max(vsz, rsz), rp))


def off(rva):
    for va, sz, rp in secs:
        if va <= rva < va + sz:
            return rp + rva - va
    raise ValueError(hex(rva))


def cstr(rva):
    o = off(rva)
    return d[o:d.index(b"\0", o)].decode()


(_, _, _, _, _, base, nfunc, nname, afunc, aname, aord) = struct.unpack_from("<IIHHIIIIIII", d, off(exp_rva))
names = {}
for i in range(nname):
    nrva = struct.unpack_from("<I", d, off(aname) + 4 * i)[0]
    idx = struct.unpack_from("<H", d, off(aord) + 2 * i)[0]
    names[idx] = cstr(nrva)
exports = []
for idx in range(nfunc):
    if struct.unpack_from("<I", d, off(afunc) + 4 * idx)[0] == 0:
        continue
    exports.append((base + idx, names.get(idx)))

with open(os.path.join(ROOT, "src", "winmm.def"), "w", newline="\n") as f:
    f.write("LIBRARY winmm\nEXPORTS\n")
    for i, (ordn, name) in enumerate(exports):
        if name:
            f.write("    %s=fwd_%d @%d\n" % (name, i, ordn))
        else:
            f.write("    ord%d=fwd_%d @%d NONAME\n" % (ordn, i, ordn))
with open(os.path.join(ROOT, "src", "winmm_exports.inc"), "w", newline="\n") as f:
    f.write("// generated by tools/gen_winmm_proxy.py: X(index, ordinal, \"name\" or nullptr)\n")
    for i, (ordn, name) in enumerate(exports):
        f.write('X(%d, %d, %s)\n' % (i, ordn, '"%s"' % name if name else "nullptr"))
print(len(exports), "exports,", sum(1 for _, n in exports if not n), "by ordinal only")
