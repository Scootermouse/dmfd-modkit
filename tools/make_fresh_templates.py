"""Developers only: write src/fresh_classes.inc, the six base classes' records as a brand-new
contract holds them (level 1, starting gear, default color and voice), for extra classes
that start fresh instead of as a copy of the player's character.

The records are taken from a save made right after installing the game (contract 1, before any
character was created) and laid out like the content mod keeps an extra class's data: the
class's byte ranges in section B (name area 0x34, field 2, then the nine blocks).

usage: python -I tools/make_fresh_templates.py "<...>\\SystemData.bin.new-install"
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import save  # noqa: E402

REC = 0x5C
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "fresh_classes.inc")


def ranges(m, B, bsize, k):
    starts = []
    for j in range(6):
        starts.append(j * REC)
        starts += [j * REC + save.u32(m, B + j * REC + 0x34 + 4 * f) for f in save.OFFSET_FIELDS]
    starts.append(bsize)
    out = [(k * REC, 0x34), (k * REC + 0x3C, 4)]
    for f in save.OFFSET_FIELDS:
        a = k * REC + save.u32(m, B + k * REC + 0x34 + 4 * f)
        out.append((a, min([x for x in starts if x > a] + [bsize]) - a))
    return out


def main(path):
    m = save.decrypt(open(path, "rb").read(), save.account_from_path(path))
    entry = save.u32(m, 0x38)
    A, B, C = (save.u32(m, entry + 4 * i) for i in range(3))
    if m[A + 2]:
        sys.exit("contract 1 already has created characters; use a save made right after installing")
    bsize = C - B
    lines = ["// Generated by tools/make_fresh_templates.py from a new-install save. Do not edit by hand.",
             "// The six base classes' data as a brand-new contract holds it, laid out like an extra",
             "// class's data in SystemData.bin.classes (name area 0x34, field 2, then the nine blocks)."]
    lens = []
    for k in range(6):
        blob = b"".join(m[B + a:B + a + n] for a, n in ranges(m, B, bsize, k))
        if blob[0x38 + 4] != 1:
            sys.exit("class %d is not level 1 in this save" % k)
        lens.append(len(blob))
        lines.append("static const uint8_t FRESH_%d[%d] = {" % (k, len(blob)))
        for i in range(0, len(blob), 24):
            lines.append("    " + ", ".join("0x%02x" % x for x in blob[i:i + 24]) + ",")
        lines.append("};")
    lines.append("static const uint8_t* const FRESH[6] = {FRESH_0, FRESH_1, FRESH_2, FRESH_3, FRESH_4, FRESH_5};")
    lines.append("static const uint32_t FRESH_LEN[6] = {%s};" % ", ".join("0x%X" % n for n in lens))
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%s bytes)" % (OUT, ", ".join(hex(n) for n in lens)))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
